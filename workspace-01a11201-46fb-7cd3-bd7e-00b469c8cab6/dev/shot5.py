import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        # desktop pass (animations paused only for capture)
        pg = await b.new_page(viewport={'width':1440,'height':960})
        errs=[]
        pg.on('pageerror', lambda e: errs.append('PAGEERROR: '+str(e)))
        pg.on('console', lambda m: errs.append(m.type+': '+m.text) if m.type=='error' else None)
        await pg.goto('file:///home/user/cardiocore.html'); await pg.wait_for_timeout(1600)
        await pg.evaluate("document.getElementById('twin').scrollIntoView({block:'center'})"); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/A-twin-fixed.png')
        await pg.evaluate("CC.go('login-patient')"); await pg.wait_for_timeout(700)
        await pg.screenshot(path='shots/B-auth-fixed.png')
        await pg.evaluate("CC.goD('analytics')"); await pg.wait_for_timeout(900)
        await pg.screenshot(path='shots/C-doc-analytics.png')
        await pg.evaluate("CC.goD('patients')"); await pg.wait_for_timeout(800)
        await pg.screenshot(path='shots/D-doc-patients.png')
        await pg.evaluate("CC.goP('appts')"); await pg.wait_for_timeout(900)
        await pg.screenshot(path='shots/E-patient-appts.png')
        await pg.evaluate("CC.goP('records')"); await pg.wait_for_timeout(800)
        await pg.screenshot(path='shots/F-patient-records.png')
        await pg.evaluate("CC.goP('home'); CC.shareModal()"); await pg.wait_for_timeout(700)
        await pg.screenshot(path='shots/H-share.png')
        print('desktop errors:', len(errs), errs[:6])
        # mobile pass with reduced motion (capture-stable, also proves the a11y path)
        for name, sz in [('mobile', 390), ('tablet', 820)]:
            m = await b.new_page(viewport={'width':sz,'height':844}, device_scale_factor=2, reduced_motion='reduce')
            await m.goto('file:///home/user/cardiocore.html'); await m.wait_for_timeout(1500)
            await m.screenshot(path=f'shots/I-{name}-hero.png', timeout=20000)
            await m.evaluate("CC.patientLogin(new Event('submit'))"); await m.wait_for_timeout(1600)
            await m.screenshot(path=f'shots/J-{name}-app.png', timeout=20000)
            await m.evaluate("CC.go('login-doctor')"); await m.wait_for_timeout(700)
            await m.screenshot(path=f'shots/K-{name}-auth.png', timeout=20000)
            await m.close()
            print(name, 'done')
        await b.close()
asyncio.run(main())
