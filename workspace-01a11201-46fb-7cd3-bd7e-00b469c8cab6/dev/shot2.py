import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page(viewport={'width':1440,'height':960})
        errs=[]
        pg.on('pageerror', lambda e: errs.append('PAGEERROR: '+str(e)))
        pg.on('console', lambda m: errs.append(m.type+': '+m.text) if m.type=='error' else None)
        await pg.goto('file:///home/user/cardiocore.html'); await pg.wait_for_timeout(1800)
        await pg.evaluate("document.getElementById('twin').scrollIntoView({block:'center'})"); await pg.wait_for_timeout(700)
        await pg.screenshot(path='shots/A-twin-fixed.png')
        await pg.evaluate("CC.go('login-patient')"); await pg.wait_for_timeout(900)
        await pg.screenshot(path='shots/B-auth-fixed.png')
        await pg.evaluate("CC.goD('analytics')"); await pg.wait_for_timeout(1200)
        await pg.screenshot(path='shots/C-doc-analytics.png')
        await pg.evaluate("CC.goD('patients')"); await pg.wait_for_timeout(900)
        await pg.screenshot(path='shots/D-doc-patients.png')
        await pg.evaluate("CC.goP('appts')"); await pg.wait_for_timeout(1200)
        await pg.screenshot(path='shots/E-patient-appts.png')
        await pg.evaluate("CC.goP('records')"); await pg.wait_for_timeout(1000)
        await pg.screenshot(path='shots/F-patient-records.png')
        await pg.evaluate("CC.goP('meds')"); await pg.wait_for_timeout(1000)
        await pg.screenshot(path='shots/G-patient-meds.png')
        await pg.evaluate("CC.goP('home'); CC.shareModal()"); await pg.wait_for_timeout(800)
        await pg.screenshot(path='shots/H-share.png')
        await pg.evaluate("CC.closeModal()")
        # mobile
        m = await b.new_page(viewport={'width':390,'height':844}, device_scale_factor=2)
        await m.goto('file:///home/user/cardiocore.html'); await m.wait_for_timeout(2000)
        await m.screenshot(path='shots/I-mobile-hero.png')
        await m.evaluate("CC.patientLogin(new Event('submit'))"); await m.wait_for_timeout(1800)
        await m.screenshot(path='shots/J-mobile-app.png')
        await m.evaluate("CC.go('login-doctor')"); await m.wait_for_timeout(900)
        await m.screenshot(path='shots/K-mobile-auth.png')
        print('CONSOLE ERRORS:', len(errs))
        for e in errs[:20]: print(' -', e[:240])
        await b.close()
asyncio.run(main())
